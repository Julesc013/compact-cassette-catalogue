[CmdletBinding()]
param()

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

$repositoryRoot = Split-Path -Parent $PSScriptRoot
$branchContract = & (Join-Path $PSScriptRoot 'get-branch-contract.ps1') `
    -RepositoryRoot $repositoryRoot
$identity = & (Join-Path $PSScriptRoot 'get-release-identity.ps1')
$productVersion = $identity.ProductVersion
$releaseStage = $identity.ReleaseStage
$releaseChannel = $identity.ReleaseChannel
$updateFeedUrl = $identity.UpdateFeedUrl
$releaseDate = $identity.ReleaseDate
$assemblyVersion = $identity.AssemblyVersion
$fileVersion = $identity.FileVersion
$catalogueFormatVersion = $identity.CatalogueFormatVersion
$informationalVersion = $identity.InformationalVersion

$buildInfo = @"
' <auto-generated />
' Generated by build/sync-version.ps1 from build/Version.props.

Public Module C3BuildInfo

    Public Const VERSION As String = "$productVersion"
    Public Const VERSIONSTAGE As String = "$releaseStage"
    Public ReadOnly VERSIONDATE As DateTime = New DateTime($($releaseDate.Year), $($releaseDate.Month), $($releaseDate.Day), 0, 0, 0, DateTimeKind.Local)

    Public Const VERSIONFILE As String = "$catalogueFormatVersion"
    Public ReadOnly VERSIONFILESUPPORTED As String() = {"$catalogueFormatVersion"}

    Public Const ReleaseChannel As String = "$releaseChannel"
    Public Const UpdateFeedUrl As String = "$updateFeedUrl"
    Public Const AssemblyVersion As String = "$assemblyVersion"
    Public Const FileVersion As String = "$fileVersion"
    Public Const InformationalVersion As String = "$informationalVersion"

End Module
"@

$versionAssemblyInfo = @"
' <auto-generated />
' Generated by build/sync-version.ps1 from build/Version.props.

Imports System.Reflection

<Assembly: AssemblyVersion("$assemblyVersion")>
<Assembly: AssemblyFileVersion("$fileVersion")>
<Assembly: AssemblyInformationalVersion("$informationalVersion")>
"@

$updateBranches = @"
' <auto-generated />
' Generated by build/sync-version.ps1 from build/branches.json.

Namespace Updates

    Friend Module C3UpdateBranches

        Public Const AlphaFeedBranch As String = "$($branchContract.CurrentIntegration)"
        Public Const PublishedFeedBranch As String = "$($branchContract.CurrentQualified)"

    End Module

End Namespace
"@

$channelManifestPath = & (Join-Path $PSScriptRoot 'get-update-manifest-path.ps1') `
    -Identity $identity `
    -RepositoryRoot $repositoryRoot
$manifestDirectory = Split-Path -Parent $channelManifestPath
$buildInfoPath = Join-Path $repositoryRoot 'src\C3.WinForms\Generated\BuildInfo.g.vb'
$versionAssemblyInfoPath = Join-Path $repositoryRoot 'src\Shared\Generated\VersionAssemblyInfo.g.vb'
$updateBranchesPath = Join-Path $repositoryRoot 'src\Shared\Generated\UpdateBranches.g.vb'

$utf8WithoutBom = New-Object Text.UTF8Encoding($false)
if (-not [IO.Directory]::Exists($manifestDirectory)) {
    [IO.Directory]::CreateDirectory($manifestDirectory) | Out-Null
}

$releaseDateText = $releaseDate.ToString(
    'yyyy-MM-dd',
    [Globalization.CultureInfo]::InvariantCulture)
# Release identity parsing constrains every interpolated value below to its
# canonical ASCII form, so this fixed template is safe and byte-deterministic.
$channelManifestJson = @(
    '{'
    '  "schemaVersion": 1,'
    '  "product": "Compact Cassette Catalogue",'
    '  "productId": "c3",'
    '  "channel": "' + $releaseChannel + '",'
    '  "version": "' + $productVersion + '",'
    '  "stage": "' + $releaseStage + '",'
    '  "informationalVersion": "' + $informationalVersion + '",'
    '  "releaseDate": "' + $releaseDateText + '",'
    '  "catalogueWriteFormat": "' + $catalogueFormatVersion + '",'
    '  "published": false,'
    '  "releaseUrl": null,'
    '  "checksumManifest": null,'
    '  "packages": []'
    '}'
) -join "`n"

[IO.File]::WriteAllText($channelManifestPath, $channelManifestJson + "`n", $utf8WithoutBom)
[IO.File]::WriteAllText($buildInfoPath, $buildInfo, $utf8WithoutBom)
[IO.File]::WriteAllText($versionAssemblyInfoPath, $versionAssemblyInfo, $utf8WithoutBom)
[IO.File]::WriteAllText($updateBranchesPath, $updateBranches, $utf8WithoutBom)

$manifestPathDisplay = $channelManifestPath.Substring($repositoryRoot.Length + 1)
Write-Host "Synchronized C3 $informationalVersion metadata to '$manifestPathDisplay'."
